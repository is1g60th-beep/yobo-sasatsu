function equipChecks(j){
  const out = [];
  for (const r of j) {
    if (r.status === 'no' || r.cat === '防火管理等') continue;
    const id = 'e:' + r.name;
    out.push({id: id + ':set', cat:'消防用設備等（個別）', text:`${r.name} が基準どおり設置されているか`, basis:`消防法17条1項、${r.basis}`, cond: r.status === 'chk' ? '要確認の設備' : '', fix:`${r.name}を技術上の基準に従って設置すること`});
    const hint = EQUIP_HINT[r.name] || Object.entries(EQUIP_HINT).find(([k]) => r.name.startsWith(k))?.[1] || '外観・機能';
    out.push({id: id + ':keep', cat:'消防用設備等（個別）', text:`${r.name} の維持管理は良好か（${hint}）`, basis:'消防法17条1項', fix:`${r.name}の不良箇所を改修し、技術上の基準に従って維持すること`});
  }
  return out;
}

function buildChecklist(o){
  const j = judge(o);
  const st = CHECKS.filter(c => !c.when || c.when(j, o));
  const order = ['防火管理','避難施設等の管理','消防用設備等（共通）'];
  const a = st.filter(c => order.includes(c.cat)), b = st.filter(c => !order.includes(c.cat));
  return a.concat(equipChecks(j), b);
}

// ===== 揖斐郡消防組合火災予防査察規程 別表第1・第2 =====
function sasatsuClass(o, j){
  j = j || judge(o);
  const fm = j.find(r => r.name.startsWith('防火管理者の選任・消防計画'));
  const kou = fm && fm.name.includes('甲種'), otsu = fm && fm.name.includes('乙種');
  const jk = j.some(r => r.name === '自動火災報知設備' && r.status === 'req');
  const ext = j.some(r => r.name === '消火器具' && r.status === 'req');
  const tok = USE[o.use] && USE[o.use].tok;
  if (tok && (kou || jk)) return {k:1, label:'第1種査察対象物', freq:'1年に1回以上', by:'予防係員'};
  if (!tok && (kou || jk)) return {k:2, label:'第2種査察対象物', freq:'1年に1回以上', by:'消防係員'};
  if (o.hazFacility) return {k:3, label:'第3種査察対象物', freq:'1年に1回以上', by:'消防係員'};
  if (otsu || ext || o.danger) return {k:4, label:'第4種査察対象物', freq:'2年に1回以上', by:'消防係員'};
  return {k:5, label:'第5種査察対象物', freq:'消防長が別に定める', by:'予防係員及び消防係員'};
}
