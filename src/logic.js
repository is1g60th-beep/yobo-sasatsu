  if (u !== '18') {
    const qual = (tok && A >= 1000) || o.oneStair;
    add(`消防用設備等の点検・報告（${tok ? '1年' : '3年'}ごと）`, 'req', qual ? (o.oneStair ? '特定一階段等：消防設備士等による点検' : '特定・延べ1,000㎡以上：消防設備士等による点検') : (A >= 1000 ? '非特定・延べ1,000㎡以上：消防長等の指定により有資格者点検' : '関係者による点検も可'), '消防法17条の3の3、令36条、規則31条の6', '機器点検6か月・総合点検1年');
  }
